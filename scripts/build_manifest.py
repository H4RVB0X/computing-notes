#!/usr/bin/env python3
"""Regenerate content/manifest.js by scanning the content and tools folders.

Run from anywhere:  python3 scripts/build_manifest.py
The site loads every file listed in the manifest at start-up, in this order:
tools, topics, quizzes, exam, flashcards, trace, problems.
"""
import os, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent / "site"
GROUPS = [("tools", "tools"), ("content/topics", "topics"), ("content/quizzes", "quizzes"),
          ("content/exam", "exam"), ("content/flashcards", "flashcards"), ("content/trace", "trace"),
          ("content/problems", "problems")]

def natural(s):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", s)]

lines = ["/* AUTO-GENERATED by scripts/build_manifest.py — list of files to load. Re-run the script after adding files, or add a line by hand. */",
         "window.CS = window.CS || {};", "CS.manifest = ["]
total = 0
for folder, label in GROUPS:
    d = ROOT / folder
    if not d.exists():
        continue
    files = sorted([f for f in os.listdir(d) if f.endswith(".js")], key=natural)
    if files:
        lines.append(f"  // {label}")
    for f in files:
        lines.append(f'  "{folder}/{f}",')
        total += 1
lines.append("];")
(ROOT / "content" / "manifest.js").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"manifest.js written with {total} files")
