#!/usr/bin/env python3
"""Generate ../COVERAGE.md: every AQA spec point → page → status.

Status is derived automatically: a point is 'Covered' when its page has a topic file, a quiz and
exam questions; 'Partial' when the page has notes but no quiz/exam; 'Missing' when there is no topic file.
Hand-written notes (uncertainties, gaps filled from own knowledge) live in dev/coverage_notes.md and
are appended verbatim.
"""
import json, os, re, subprocess, sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
NODE = r"""
const vm=require("vm"),fs=require("fs"),path=require("path");const root=process.env.SITE_ROOT;
const ctx={console};ctx.window=ctx;vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root,"content/sections.js"),"utf8"),ctx);
console.log(JSON.stringify(ctx.CS.sections));
"""
res = subprocess.run(["node", "-e", NODE], capture_output=True, text=True, env=dict(os.environ, SITE_ROOT=str(ROOT)))
sections = json.loads(res.stdout.strip().splitlines()[-1])
def exists(kind, tid):
    return (ROOT / "content" / kind / (tid + (".md.js" if kind == "topics" else ".js"))).exists()
tools_in = {}
for f in (ROOT / "content" / "topics").glob("*.md.js"):
    tid = f.name.replace(".md.js", "")
    tools_in[tid] = sorted(set(re.findall(r"\{\{tool:([^\s}]+)", f.read_text(encoding="utf-8"))))
registered_tools = set()
for f in (ROOT / "tools").glob("*.js"):
    m = re.search(r"id:\s*[\"']([^\"']+)[\"']", f.read_text(encoding="utf-8"))
    if m: registered_tools.add(m.group(1))
rows = []; counts = {"Covered": 0, "Partial": 0, "Missing": 0}
for s in sections:
    for t in s["topics"]:
        tid = t["id"]
        has_topic, has_quiz, has_exam = exists("topics", tid), exists("quizzes", tid), exists("exam", tid)
        status = "Covered" if (has_topic and has_quiz and has_exam) else ("Partial" if has_topic else "Missing")
        extras = []
        if has_topic and not has_quiz: extras.append("no quiz")
        if has_topic and not has_exam: extras.append("no exam Qs")
        missing_tools = [x for x in tools_in.get(tid, []) if x not in registered_tools]
        if missing_tools: extras.append("tool(s) not built: " + ", ".join(missing_tools))
        for p in t.get("specPoints", []):
            counts[status] += 1
            rows.append((s["spec"] or s["id"], p["id"], p["text"], tid, t["title"], status + ((" (" + "; ".join(extras) + ")") if extras else "")))
out = ["# COVERAGE.md — AQA 7517 specification coverage audit", "",
       "Generated by `revision-site/dev/build_coverage.py` from `content/sections.js` and the content folders. "
       "Every row is one specification point. **Covered** = the page has notes, a quiz and exam-style questions. "
       "Spec point ids follow the AQA numbering; where one spec paragraph has several bullets they are split with a letter suffix (e.g. 4.1.1.2a).", "",
       f"**Summary:** {counts['Covered']} covered · {counts['Partial']} partial · {counts['Missing']} missing, out of {sum(counts.values())} spec points across {sum(len(s['topics']) for s in sections)} pages.", "",
       "| Section | Spec point | Requirement | Page | Status |", "|---|---|---|---|---|"]
for sec, pid, text, tid, title, status in rows:
    out.append(f"| {sec} | `{pid}` | {text.replace('|', '/')} | [{tid} {title}](revision-site/index.html#/topic/{tid}) | {status} |")
notes = ROOT / "dev" / "coverage_notes.md"
if notes.exists():
    out += ["", notes.read_text(encoding="utf-8").rstrip()]
(ROOT.parent / "COVERAGE.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"COVERAGE.md written: {counts}")
